#!/usr/bin/env python3
"""Compare schematic connectivity with PCB pad connectivity.

Run inside the pinned KiCad container (it provides the `pcbnew` module):

    python3 connectivity_check.py /work

The comparison is name-independent: net names generated by eeschema use pin
names while pcbnew uses pad numbers, so the check compares the *partition* of
(ref, pin) nodes. Every pair of nodes that shares a net in the schematic must
share a net on the PCB and vice versa. Differences are reported explicitly.
"""
from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

import pcbnew


def schematic_nets(netlist: Path) -> dict[tuple[str, str], str]:
    text = netlist.read_text(encoding="utf8", errors="replace")
    node_to_net: dict[tuple[str, str], str] = {}
    for name, body in re.findall(
        r'\(net \(code "\d+"\) \(name "([^"]+)"\)(.*?)(?=\(net \(code|\Z)',
        text,
        re.S,
    ):
        for ref, pin in re.findall(
            r'\(node \(ref "([^"]+)"\) \(pin "([^"]+)"\)', body
        ):
            node_to_net[(ref, pin)] = name
    return node_to_net


def board_nets(board_path: Path) -> dict[tuple[str, str], str]:
    board = pcbnew.LoadBoard(str(board_path))
    node_to_net: dict[tuple[str, str], str] = {}
    for footprint in board.GetFootprints():
        ref = footprint.GetReference()
        for pad in footprint.Pads():
            net = pad.GetNetname()
            if net:
                node_to_net[(ref, pad.GetNumber())] = net
    return node_to_net


def split_nets(
    nets: dict[tuple[str, str], str],
    other: dict[tuple[str, str], str],
    common: set[tuple[str, str]],
) -> list[tuple[str, list[str]]]:
    groups: dict[str, set[tuple[str, str]]] = defaultdict(set)
    for node, net in nets.items():
        if node in common:
            groups[net].add(node)
    bad = []
    for net, members in groups.items():
        counterparts = {other[node] for node in members}
        if len(counterparts) > 1:
            bad.append((net, sorted(counterparts)))
    return bad


def main() -> int:
    work = Path(sys.argv[1] if len(sys.argv) > 1 else "/work")
    sch = schematic_nets(work / "manufacturing/assembly/v0.4.4d.net")
    pcb = board_nets(work / "v0.4.4d.kicad_pcb")

    common = set(sch) & set(pcb)
    sch_split = split_nets(sch, pcb, common)
    pcb_split = split_nets(pcb, sch, common)
    only_sch = sorted(set(sch) - set(pcb))
    only_pcb = sorted(set(pcb) - set(sch))

    passed = not sch_split and not pcb_split
    lines = [
        "Schematic-to-PCB connectivity comparison",
        "=======================================",
        f"schematic nodes: {len(sch)}",
        f"pcb nodes:       {len(pcb)}",
        f"common nodes:    {len(common)}",
        f"schematic nets split on pcb: {len(sch_split)}",
        f"pcb nets split on schematic: {len(pcb_split)}",
        f"nodes only in schematic: {len(only_sch)}",
        f"nodes only in pcb:       {len(only_pcb)}",
        "",
    ]
    if only_sch:
        lines.append(
            "Schematic-only nodes (expected: unpopulated Arduino ICSP header pins):"
        )
        for ref, pin in only_sch:
            lines.append(f"  {ref}.{pin}")
        lines.append("")
    if only_pcb:
        lines.append("PCB-only nodes:")
        for ref, pin in only_pcb:
            lines.append(f"  {ref}.{pin}")
        lines.append("")
    for label, bad in (("schematic", sch_split), ("pcb", pcb_split)):
        if bad:
            lines.append(f"{label} nets that are split in the other representation:")
            for net, counterparts in bad:
                lines.append(f"  {net} -> {', '.join(counterparts)}")
            lines.append("")
    lines.append(f"RESULT: {'PASS' if passed else 'FAIL'}")
    out = "\n".join(lines) + "\n"
    (work / "verification/connectivity.txt").write_text(out, encoding="utf8")
    print(out)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
